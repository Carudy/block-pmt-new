#!/bin/bash
#
# 打包本次实验结果到 res/ 目录，命名包含全部参数：
#   res_{schema}_ns{num_shards}_is{inject_speed}_nn{num_nodes}_mcb{Max_Commit_Block}_mb{MaxBlockSize}_{YYYYMMDDHHMM}.zip
#   例：res_preempt_ns2_is500_nn16_mcb15_mb2000_202609141505.zip
#
# zip 内包含：
#   - log/           本次运行的全部 CSV 日志
#   - log/params.txt 本次运行的参数（schema / num_shards / num_nodes / Inject_speed / Max_Commit_Block / MaxBlockSize）
#   - params/config.go 配置快照（便于复现）
#
# schema / Inject_speed / Max_Commit_Block / MaxBlockSize 从 params/config.go 的【生效行】读取；
# num_shards / num_nodes 默认从 run.sh 读取，也可用环境变量覆盖：
#   N_SHARD=4 N_NODES=16 ./zip_res.sh

set -u

source ./schema_detect.sh
schema_detect || exit 1

# 从 config.go 读取某数值字段的生效值
cfg_num() { sed -n "s/^[[:space:]]*$1:[[:space:]]*\([0-9][0-9]*\).*/\1/p" params/config.go | head -n 1; }

MAX_COMMIT_BLOCK=$(cfg_num Max_Commit_Block)
MAXBLOCK_SIZE=$(cfg_num MaxBlockSize)

# preempt_escrow 的协议参数：写入 params.txt，便于复现（旧 schema 不输出，保持文件不变）
if [ "${SCHEMA}" = "preempt_escrow" ]; then
    ESC_QUIESCE_DELAY=$(cfg_num QuiesceDelayBlocks)
    ESC_MIG_TIMEOUT=$(cfg_num MigrationTimeoutBlocks)
    ESC_SETTLE_WAIT=$(cfg_num SettlementWaitBlocks)
    ESC_MAX_BATCH=$(cfg_num MaxEscrowBatchTxs)
    ESC_GAP_REPAIR=$(cfg_num EscrowGapRepairBlocks)
    ESC_INIT_BAL=$(sed -n 's/^[[:space:]]*EscrowInitBalance:[[:space:]]*\(.*\),[[:space:]]*$/\1/p' params/config.go | head -n 1)
fi

# 分片数：环境变量 > run.sh（num_shards=2 或 num_shards="${NUM_SHARDS:-2}"）
if [ -z "${N_SHARD:-}" ]; then
    N_SHARD=$(sed -n 's/^[[:space:]]*num_shards=\([0-9][0-9]*\).*/\1/p' run.sh | head -n 1)
fi
if [ -z "${N_SHARD:-}" ]; then
    N_SHARD=$(sed -n 's/^[[:space:]]*num_shards=.*:-[[:space:]]*\([0-9][0-9]*\).*/\1/p' run.sh | head -n 1)
fi
if [ -z "${N_SHARD:-}" ]; then
    echo "ERROR: 无法确定分片数（可用 N_SHARD=2 ./zip_res.sh 覆盖）" >&2
    exit 1
fi

# 每分片节点数：环境变量 > run.sh
if [ -z "${N_NODES:-}" ]; then
    N_NODES=$(sed -n 's/^[[:space:]]*num_nodes=\([0-9][0-9]*\).*/\1/p' run.sh | head -n 1)
fi
if [ -z "${N_NODES:-}" ]; then
    N_NODES=$(sed -n 's/^[[:space:]]*num_nodes=.*:-[[:space:]]*\([0-9][0-9]*\).*/\1/p' run.sh | head -n 1)
fi
N_NODES="${N_NODES:-NA}"

STAMP=$(date +%Y%m%d%H%M)
NAME="res_${SCHEMA}_ns${N_SHARD}_is${INJECT_SPEED}_nn${N_NODES}_mcb${MAX_COMMIT_BLOCK:-NA}_mb${MAXBLOCK_SIZE:-NA}_${STAMP}"
OUT="res/${NAME}.zip"

# 把本次运行参数写进 log/params.txt（会随 log/ 一起打入 zip）
mkdir -p log
PARAM_FILE="log/params.txt"
{
    echo "# Run parameters (auto-generated by zip_res.sh)"
    echo "timestamp = ${STAMP}"
    echo "scheme    = ${SCHEMA}"
    echo "ns        = ${N_SHARD}"
    echo "is        = ${INJECT_SPEED}"
    echo "nn        = ${N_NODES}"
    echo "mcb       = ${MAX_COMMIT_BLOCK:-?}"
    echo "mb        = ${MAXBLOCK_SIZE:-?}"
    if [ "${SCHEMA}" = "preempt_escrow" ]; then
        echo "# preempt_escrow protocol knobs"
        echo "quiesce_delay  = ${ESC_QUIESCE_DELAY:-?}   # QuiesceDelayBlocks"
        echo "mig_timeout    = ${ESC_MIG_TIMEOUT:-?}   # MigrationTimeoutBlocks"
        echo "settle_wait    = ${ESC_SETTLE_WAIT:-?}   # SettlementWaitBlocks"
        echo "max_batch_txs  = ${ESC_MAX_BATCH:-?}   # MaxEscrowBatchTxs (0 = unlimited)"
        echo "gap_repair     = ${ESC_GAP_REPAIR:-?}   # EscrowGapRepairBlocks (0 = disabled)"
        echo "init_balance   = ${ESC_INIT_BAL:-?}   # EscrowInitBalance"
    fi
    echo "# (ns=num_shards, is=inject_speed, nn=num_nodes, mcb=Max_Commit_Block, mb=MaxBlockSize)"
} > "${PARAM_FILE}"

mkdir -p res
rm -f "${OUT}"
zip -r "${OUT}" log
# 配置快照，便于复现
[ -f params/config.go ] && zip "${OUT}" params/config.go

cp "${OUT}" /disc/home/dy/caddy/site

echo "Wrote ${OUT}  (schema=${SCHEMA}, ns=${N_SHARD}, is=${INJECT_SPEED}, nn=${N_NODES}, mcb=${MAX_COMMIT_BLOCK:-NA}, mb=${MAXBLOCK_SIZE:-NA})"
